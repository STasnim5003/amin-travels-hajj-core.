from sqlalchemy import Column, Integer, String, Boolean, Float
from sqlalchemy.dialects.postgresql import JSONB

from data.model.base_mixin_model import Base, BaseMixinModel


class UmrahRequisitionModel(Base, BaseMixinModel):
    __tablename__ = "umrah_requisition"
    __table_args__ = {"schema": "core"}

    id = Column(Integer, primary_key=True, index=True)
    name = Column(String, nullable=True)
    number_of_traveller = Column(Integer, nullable=True)
    adult_traveller = Column(Integer, nullable=True)
    other_traveller = Column(JSONB, nullable=True)
    is_visa = Column(Boolean, nullable=True)
    with_hotel_brn = Column(Boolean, nullable=True)
    air_ticket = Column(Boolean, nullable=True)
    air_ticket_category = Column(String, nullable=True)
    airline_preference = Column(String, nullable=True)
    flight_data = Column(JSONB, nullable=True)
    hotel_info = Column(JSONB, nullable=True)
    transport = Column(JSONB, nullable=True)
    remarks = Column(String, nullable=True)
    agency_name = Column(String, nullable=False)
    food = Column(Boolean, nullable=True)
    mobile_no = Column(String, nullable=True)
    flight_date_option_1 = Column(JSONB, nullable=True)
    flight_date_option_2 = Column(JSONB, nullable=True)
    flight_date_final = Column(JSONB, nullable=True)
    passport_info = Column(JSONB, nullable=True)
    ziara = Column(Boolean, nullable=True)
    visa_price = Column(JSONB, nullable=True)
    air_ticket_price = Column(JSONB, nullable=True)
    train_price = Column(JSONB, nullable=True)
    ziara_price =Column(JSONB, nullable=True)
    guide_price = Column(JSONB, nullable=True)
    food_price = Column(JSONB, nullable=True)
    others_price = Column(JSONB, nullable=True)
    per_head_price_adult = Column(Float, nullable=True)
    per_head_price_child = Column(Float, nullable=True)
    per_head_price_infant = Column(Float, nullable=True)
    total_vendor_price = Column(Float, nullable=True)
    total_service_charge = Column(Float, nullable=True)
    total_price = Column(Float, nullable=True)
    is_confirmed = Column(Boolean, nullable=True)
    return_date_option_1 = Column(JSONB, nullable=True)
    return_date_option_2= Column(JSONB, nullable=True)
    return_date_final= Column(JSONB, nullable=True)
    exchange_rate= Column(Float, nullable=True)
    child_service = Column(JSONB, nullable=True)
    infant_service = Column(JSONB, nullable=True)
    total_due = Column(Float, nullable=True)
    total_payment = Column(Float, nullable=True)
    amin_office_code = Column(String, nullable=True)
    requisition_type = Column(String, nullable=True)
    b2b_agent_name = Column(String, nullable=True)
    sales_person = Column(String, nullable=True)
    train = Column(Boolean, nullable=True)
    guide = Column(Boolean, nullable=True)
    discount = Column(Float, nullable=True)
    is_child_included_with_bed_transport = Column(Boolean, nullable=True)
    confirmed_remarks = Column(String, nullable=True)
    confirmed_pilgrims_family_group = Column(String, nullable=True)
    confirmed_pilgrims_basic_info = Column(JSONB, nullable=True)
    confirmed_pilgrims_flight_info = Column(JSONB, nullable=True)
    confirmed_pilgrims_hotel_info = Column(JSONB, nullable=True)
    confirmed_pilgrims_transport_info = Column(JSONB, nullable=True)
    confirmed_pilgrims_ksa_part_data_submission = Column(JSONB, nullable=True)
    reference = Column(String, nullable=True)
    service_confirmation_status = Column(JSONB, nullable=True)
    emergency_contract_person = Column(JSONB, nullable=True)
    b2b_type = Column(String, nullable=True)
    b2b_partial_guests = Column(JSONB, nullable=True)
    b2b_partial_description = Column(JSONB, nullable=True)
    extra_service_charge = Column(Float, nullable=True)


class UmrahVendorsPriceModel(Base, BaseMixinModel):
    __tablename__ = "umrah_vendor_prices"
    __table_args__ = {"schema": "core"}

    id = Column(Integer, primary_key=True, index=True)
    exchange_rate = Column(Float, nullable=True)
    umrah_requisition_id = Column(Integer, nullable=False,unique=True)
    hotel_vendors_price = Column(JSONB, nullable=True)
    transport_vendors_price = Column(JSONB, nullable=True)
    air_ticket_vendors_price = Column(JSONB, nullable=True)
    visa_vendors_price = Column(JSONB, nullable=True)
    train_vendors_price = Column(JSONB, nullable=True)
    ziara_vendors_price = Column(JSONB, nullable=True)
    food_vendors_price = Column(JSONB, nullable=True)
    others_vendors_price = Column(JSONB, nullable=True)
    guide_vendors_price = Column(JSONB, nullable=True)
    extra_service_charge=Column(Float, nullable=True)
